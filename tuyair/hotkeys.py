"""Generate an AutoHotkey v2 script (Windows) from the "hotkeys" section of the config.

Actions:
  "@panel"            open / close the control window
  "ac on" "ac off" "ac toggle"
  "ac temp +1"  "ac temp -1"  "ac mode next"  "ac fan next"  "ac cmd powerful" ...
  "tv_power"          any saved button name (several names = sent in order)

Keys are written like "ctrl+alt+a", "ctrl+shift+f5", "win+alt+1". Letters and digits
are converted to virtual-key codes so they work with every keyboard layout.
"""
import os
import sys
from pathlib import Path

DEFAULT_HOTKEYS = {
    "ctrl+alt+a": "@panel",
    "ctrl+alt+i": "ac on",
    "ctrl+alt+o": "ac off",
    "ctrl+alt+p": "ac cmd powerful",
    "ctrl+alt+s": "ac cmd swing",
    "ctrl+alt+d": "ac cmd airflow",
    "ctrl+alt+h": "ac cmd airflow_h",
    "ctrl+alt+up": "ac temp +1",
    "ctrl+alt+down": "ac temp -1",
}

MODS = {"ctrl": "^", "control": "^", "alt": "!", "shift": "+", "win": "#"}
NAMED = {"up": "Up", "down": "Down", "left": "Left", "right": "Right", "space": "Space",
         "enter": "Enter", "tab": "Tab", "home": "Home", "end": "End", "pgup": "PgUp", "pgdn": "PgDn",
         "insert": "Insert", "delete": "Delete"}


def ahk_key(combo):
    parts = [p.strip().lower() for p in combo.replace("-", "+").split("+") if p.strip()]
    if not parts:
        raise ValueError("empty hotkey")
    *mods, key = parts
    prefix = ""
    for m in mods:
        if m not in MODS:
            raise ValueError(f"Unknown modifier '{m}' in '{combo}'")
        prefix += MODS[m]
    if len(key) == 1 and key.isalnum():
        name = "vk%02X" % ord(key.upper())
    elif key.startswith("f") and key[1:].isdigit() and 1 <= int(key[1:]) <= 24:
        name = key.upper()
    elif key.startswith("numpad") and key[6:].isdigit():
        name = "Numpad" + key[6:]
    elif key in NAMED:
        name = NAMED[key]
    else:
        raise ValueError(f"Unsupported key '{key}' in '{combo}'")
    return prefix + name


def pythonw():
    exe = Path(sys.executable)
    for cand in (exe.with_name("pythonw.exe"), exe.parent.parent / "pythonw.exe"):
        if cand.exists():
            return str(cand)
    return str(exe)


def ahk_string(s):
    return '"' + s.replace('"', '""') + '"'


def build_script(cfg):
    hotkeys = cfg.get("hotkeys") or DEFAULT_HOTKEYS
    pkg_parent = str(Path(__file__).resolve().parent.parent)
    lines = [
        "#Requires AutoHotkey v2.0",
        "#SingleInstance Force",
        "; Generated by: tuyair hotkeys   (edit the \"hotkeys\" section of config.json and run it again)",
        "",
        f"PY := {ahk_string(pythonw())}",
        f"CFG := {ahk_string(str(cfg.path))}",
        f"WORKDIR := {ahk_string(pkg_parent)}",
        "SHOW_TIP := true",
        "",
        "Tuyair(args, tip) {",
        "    if SHOW_TIP {",
        "        ToolTip(tip)",
        "        SetTimer(() => ToolTip(), -1000)",
        "    }",
        "    try Run(Format('\"{1}\" -m tuyair --config \"{2}\" {3}', PY, CFG, args), WORKDIR, \"Hide\")",
        "    catch as e",
        "        MsgBox(\"Could not start Python:`n\" PY \"`n`n\" e.Message, \"tuyair\", \"Icon!\")",
        "}",
        "",
    ]
    for combo, action in hotkeys.items():
        key = ahk_key(combo)
        action = action.strip()
        if action == "@panel":
            args = "panel"
        elif action.startswith("ac "):
            args = action
        else:
            args = "send " + action
        lines.append(f"{key}:: Tuyair({ahk_string(args)}, {ahk_string(action)})   ; {combo}")
    return "\n".join(lines) + "\n"


def startup_folder():
    appdata = os.environ.get("APPDATA")
    if not appdata:
        return None
    return Path(appdata) / "Microsoft" / "Windows" / "Start Menu" / "Programs" / "Startup"
